import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { rolldown } from "rolldown";

const root = fileURLToPath(new URL("..", import.meta.url));
const outputPath = path.join(root, "src/generated/curated-gallery-contract.js");
const checkOnly = process.argv.includes("--check");
const zod = JSON.parse(await readFile(path.join(root, "node_modules/zod/package.json"), "utf8"));
const license = await readFile(path.join(root, "node_modules/zod/LICENSE"), "utf8");
const bundle = await rolldown({
  input: path.join(root, "src/lib/curated-gallery-contract.ts"),
  treeshake: true,
});
let generated;
try {
  const { output } = await bundle.generate({ format: "esm", minify: true });
  const chunk = output[0];
  if (output.length !== 1 || chunk?.type !== "chunk" || chunk.imports.length) {
    throw new Error("The browser contract must be one self-contained module.");
  }
  generated = `/*! Generated by scripts/build-curated-gallery-contract.mjs. Do not edit.\n * Zod ${zod.version}; source: src/lib/curated-gallery-contract.ts\n * ${license.trim().replaceAll("\n", "\n * ")}\n */\n${chunk.code}\n`;
} finally {
  await bundle.close();
}
if (checkOnly) {
  if (await readFile(outputPath, "utf8") !== generated) {
    throw new Error("Browser contract is stale. Run npm run contracts:generate.");
  }
  console.log("Browser contract matches its pinned dependency and canonical schema.");
} else {
  await writeFile(outputPath, generated);
  console.log(`Generated browser contract: ${Buffer.byteLength(generated)} bytes.`);
}
